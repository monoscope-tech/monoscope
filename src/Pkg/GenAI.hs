-- | Prices are USD per million tokens; a missing cache rate falls back to the input rate.
data ModelPrice = ModelPrice {input :: Double, output :: Double, cacheRead :: Maybe Double, cacheWrite :: Maybe Double, contextWindow :: Maybe Int}
  deriving stock (Eq, Show)


data Usage = Usage {input :: Double, output :: Double, cacheRead :: Double, cacheWrite :: Double}
  deriving stock (Eq, Show)


-- | Generated by scripts/update-model-prices.py from LiteLLM's MIT price table.
--
-- >>> HM.size prices > 1000
-- True
prices :: HM.HashMap Text ModelPrice
prices = maybe mempty (fmap price) $ AE.decodeStrict $(embedFile "static/model_prices.json")
  where
    price (i, o, r, w, c) = ModelPrice i o r w c :: ModelPrice


-- | The id the price table is keyed by: no provider path, region or vendor prefix,
-- version pin or Bedrock revision.
--
-- >>> map normaliseModel ["openai/gpt-4o", "us.anthropic.claude-sonnet-4-5-20250929-v1:0", "claude-3-5-sonnet@20240620", "models/gemini-2.5-pro", "GPT-4o"]
-- ["gpt-4o","claude-sonnet-4-5-20250929","claude-3-5-sonnet","gemini-2.5-pro","gpt-4o"]
normaliseModel :: Text -> Text
normaliseModel raw = unpin $ dropVendor $ snd $ T.breakOnEnd "/" $ T.toLower raw
  where
    dropVendor m = case break (\s -> any (`T.isPrefixOf` s) families) (T.splitOn "." m) of
      (_ : _, family@(_ : _)) -> T.intercalate "." family
      _ -> m
    families = ["claude", "llama", "mistral", "nova", "titan", "command", "jamba"]
    -- Bedrock pins a revision as "-v1:0"; elsewhere "-v3" is part of the name.
    unpin m = case T.break (== ':') m of
      (pre, pin) | not (T.null pin), (base, rev) <- T.breakOnEnd "-v" pre, not (T.null base), not (T.null rev), T.all isDigit rev -> T.dropEnd 2 base
      (pre, _) -> T.takeWhile (/= '@') pre


-- | Exact id, then without a date pin, then the longest known family prefix, then the
-- nearest dated release of a bare alias.
--
-- >>> (.input) <$> lookupPrice "gpt-4o-2024-08-06"
-- Just 2.5
-- >>> (.input) <$> lookupPrice "anthropic.claude-opus-4-1-20250805-v1:0"
-- Just 15.0
-- >>> (.input) <$> lookupPrice "claude-opus-4-1"
-- Just 15.0
-- >>> lookupPrice "my-finetune"
-- Nothing
lookupPrice :: Text -> Maybe ModelPrice
lookupPrice raw = asum (map (`HM.lookup` prices) (m : undated : families)) <|> dated
  where
    m = normaliseModel raw
    parts = T.splitOn "-" m
    undated = T.intercalate "-" $ reverse $ dropWhile (\p -> T.all isDigit p && T.length p `elem` [2, 4, 8]) $ reverse parts
    families = [T.intercalate "-" (take n parts) | n <- [length parts - 1, length parts - 2 .. 1]]
    dated = M.lookupGE (m <> "-") pricesByKey >>= \(k, p) -> p <$ guard ((m <> "-") `T.isPrefixOf` k)


-- | Ordered for the dated-release lookup: a bare alias sorts just before its releases.
pricesByKey :: M.Map Text ModelPrice
pricesByKey = M.fromList $ HM.toList prices


-- | Totals per the GenAI conventions include cached tokens; Anthropic-native counts
-- exclude them, which shows as cache tokens exceeding the input total.
--
-- >>> let sonnet = ModelPrice 3 15 (Just 0.3) (Just 3.75) Nothing
-- >>> estimateCost sonnet (Usage 1000000 0 0 0)
-- 3.0
-- >>> estimateCost sonnet (Usage 1000000 0 800000 0)
-- 0.84
-- >>> estimateCost sonnet (Usage 10 0 1000000 0)
-- 0.30003
-- >>> estimateCost (ModelPrice 2 8 Nothing Nothing Nothing) (Usage 1000 500 500 0)
-- 6.0e-3
estimateCost :: ModelPrice -> Usage -> Double
estimateCost p u = max 0 $ (uncached * p.input + u.cacheRead * fromMaybe p.input p.cacheRead + u.cacheWrite * fromMaybe p.input p.cacheWrite + u.output * p.output) / 1e6
  where
    cached = u.cacheRead + u.cacheWrite
    uncached = if u.input >= cached then u.input - cached else u.input


-- | Sub-cent amounts keep four decimals: a single call usually costs fractions of a cent.
--
-- >>> map formatUsd [0, 0.00004, 0.0042, 0.42, 12.3456]
-- ["$0","<$0.0001","$0.0042","$0.42","$12.35"]
formatUsd :: Double -> Text
formatUsd c
  | c <= 0 = "$0"
  | c < 0.0001 = "<$0.0001"
  | otherwise = "$" <> toText (showFFloat (Just $ if c < 0.01 then 4 else 2) c "")


-- | @gen_ai.response.finish_reasons@: an array by the conventions, a single string from some producers.
