-- | Canonical GenAI keys from whichever dialect the producer speaks. Originals are kept,
-- except indexed message keys, which are folded into one messages array.
--
-- OpenInference, with cost estimated from the price table:
--
-- >>> let oi = normalizeGenAI [("openinference.span.kind", "LLM"), ("llm.model_name", "gpt-4o"), ("llm.token_count.prompt", AE.Number 1000), ("llm.token_count.completion", AE.Number 100), ("llm.input_messages.0.message.role", "user"), ("llm.input_messages.0.message.content", "hi"), ("session.id", "s1")]
-- >>> mapMaybe (`lookup` oi) ["gen_ai.operation.name", "gen_ai.request.model", "gen_ai.usage.input_tokens", "gen_ai.usage.cost", "gen_ai.usage.cost_source", "gen_ai.conversation.id"]
-- [String "chat",String "gpt-4o",Number 1000.0,Number 3.5e-3,String "estimated",String "s1"]
-- >>> lookup "gen_ai.input.messages" oi
-- Just (Array [Object (fromList [("parts",Array [Object (fromList [("content",String "hi"),("type",String "text")])]),("role",String "user")])])
-- >>> any (T.isPrefixOf "llm.input_messages" . fst) oi
-- False
-- >>> lookup "gen_ai.input.preview" oi
-- Just (String "hi")
--
-- OpenLLMetry's indexed prompt with a tool call; the old token names; JSON-string messages:
--
-- >>> let ol = normalizeGenAI [("gen_ai.system", "openai"), ("gen_ai.request.model", "gpt-4o-mini"), ("llm.request.type", "chat"), ("gen_ai.usage.prompt_tokens", AE.Number 10), ("gen_ai.completion.0.role", "assistant"), ("gen_ai.completion.0.tool_calls.0.name", "search"), ("gen_ai.completion.0.tool_calls.0.arguments", "{\"q\":1}"), ("gen_ai.completion.0.finish_reason", "tool_calls")]
-- >>> mapMaybe (`lookup` ol) ["gen_ai.provider.name", "gen_ai.usage.input_tokens", "gen_ai.response.finish_reasons"]
-- [String "openai",Number 10.0,Array [String "tool_calls"]]
-- >>> lookup "gen_ai.output.messages" ol
-- Just (Array [Object (fromList [("finish_reason",String "tool_calls"),("parts",Array [Object (fromList [("arguments",String "{\"q\":1}"),("id",Null),("name",String "search"),("type",String "tool_call")])]),("role",String "assistant")])])
-- >>> let canonical = normalizeGenAI [("gen_ai.operation.name", "chat"), ("gen_ai.input.messages", "[{\"role\":\"user\",\"content\":\"yo\"}]")]
-- >>> lookup "gen_ai.input.preview" canonical
-- Just (String "yo")
-- >>> lookup "gen_ai.input.messages" canonical
-- Just (Array [Object (fromList [("parts",Array [Object (fromList [("content",String "yo"),("type",String "text")])]),("role",String "user")])])
--
-- Claude Code log events: string numbers, exclusive input counts made inclusive, its own cost:
--
-- >>> let cc = normalizeGenAI [("event.name", "api_request"), ("prompt.id", "98ec"), ("model", "claude-sonnet-4-5"), ("input_tokens", "10"), ("cache_read_tokens", "5000"), ("output_tokens", "20"), ("cost_usd", "0.0021"), ("session.id", "abc")]
-- >>> mapMaybe (`lookup` cc) ["gen_ai.operation.name", "gen_ai.provider.name", "gen_ai.usage.input_tokens", "gen_ai.usage.cost", "gen_ai.usage.cost_source", "gen_ai.conversation.id"]
-- [String "chat",String "anthropic",Number 5010.0,Number 2.1e-3,String "reported",String "abc"]
--
-- pi-otel: the same exclusive input, @gen_ai.system@ naming the agent rather than the provider, Pi's own cost:
--
-- >>> let p = normalizeGenAI [("gen_ai.system", "pi"), ("gen_ai.operation.name", "chat"), ("gen_ai.provider.name", "anthropic"), ("gen_ai.request.model", "claude-sonnet-4-5"), ("gen_ai.usage.input_tokens", AE.Number 10), ("gen_ai.usage.cache_read_input_tokens", AE.Number 1000), ("gen_ai.usage.cache_write_input_tokens", AE.Number 50), ("pi.cost.usd", AE.Number 0.0123)]
-- >>> mapMaybe (`lookup` p) ["gen_ai.provider.name", "gen_ai.usage.input_tokens", "gen_ai.usage.cache_write.input_tokens", "gen_ai.usage.cost", "gen_ai.usage.cost_source"]
-- [String "anthropic",Number 1060.0,Number 50.0,Number 1.23e-2,String "reported"]
--
-- A real @claude -p@ user_prompt record becomes the turn's user message:
--
-- >>> lookup "gen_ai.input.messages" $ normalizeGenAI [("event.name", "user_prompt"), ("event.sequence", AE.Number 22), ("prompt.id", "98ec"), ("prompt_length", "30"), ("prompt", "Reply with the single word: hi"), ("session.id", "1381")]
-- Just (Array [Object (fromList [("parts",Array [Object (fromList [("content",String "Reply with the single word: hi"),("type",String "text")])]),("role",String "user")])])
--
-- Vercel's outer span is an agent run: its usage aggregates its steps, so it is not priced.
--
-- >>> let v = normalizeGenAI [("ai.operationId", "ai.generateText"), ("ai.model.id", "gpt-4o"), ("ai.usage.promptTokens", AE.Number 5)]
-- >>> mapMaybe (`lookup` v) ["gen_ai.operation.name", "gen_ai.usage.input_tokens", "gen_ai.usage.cost"]
-- [String "invoke_agent"]
--
-- Records with no GenAI marker pass through untouched, even with a session, a bare model key or
-- an event name Claude Code also uses:
--
-- >>> normalizeGenAI [("session.id", "s"), ("model", "x"), ("http.request.method", "GET")]
-- [("session.id",String "s"),("model",String "x"),("http.request.method",String "GET")]
-- >>> normalizeGenAI [("event.name", "api_error"), ("session.id", "s")]
-- [("event.name",String "api_error"),("session.id",String "s")]
--
-- A model with no operation is a chat call only when it reports tokens:
--
-- >>> lookup "gen_ai.operation.name" <$> map normalizeGenAI [[("gen_ai.request.model", "gpt-4o")], [("gen_ai.request.model", "gpt-4o"), ("gen_ai.usage.input_tokens", AE.Number 3)]]
-- [Nothing,Just (String "chat")]
normalizeGenAI :: [(Text, AE.Value)] -> [(Text, AE.Value)]
normalizeGenAI kvs
  | isNothing ccEvent && not (any (\(k, _) -> any (`T.isPrefixOf` k) markers) kvs) = kvs
  | otherwise = [(k, passThrough k v) | (k, v) <- kvs, not (folded k)] <> derived
  where
    markers = ["gen_ai.", "llm.", "ai.", "openinference.", "traceloop.", "langfuse."]
    -- The guard above runs on every attribute set ingested, so it must not build the map.
    -- These event names are common elsewhere; Claude Code also stamps every event with prompt.id.
    ccEvent = guard (isJust $ lookup "prompt.id" kvs) *> lookup "event.name" kvs >>= str >>= \e -> find (== fromMaybe e (T.stripPrefix "claude_code." e)) ["api_request", "api_error", "tool_result", "user_prompt"]
    m = HM.fromList kvs
    pick k = HM.lookup k m
    firstOf = asum . map pick
    text k = pick k >>= str
    cc k = guard (isJust ccEvent) *> pick k

    op =
      text "gen_ai.operation.name"
        <|> (text "openinference.span.kind" >>= (`lookup` [("LLM", "chat"), ("TOOL", "execute_tool"), ("AGENT", "invoke_agent"), ("CHAIN", "invoke_workflow"), ("EMBEDDING", "embeddings"), ("RETRIEVER", "retrieval"), ("RERANKER", "rerank"), ("GUARDRAIL", "guardrail"), ("EVALUATOR", "evaluate")]))
        <|> (text "llm.request.type" >>= (`lookup` [("chat", "chat"), ("completion", "text_completion"), ("embedding", "embeddings"), ("rerank", "rerank")]))
        <|> (text "traceloop.span.kind" >>= (`lookup` [("workflow", "invoke_workflow"), ("agent", "invoke_agent"), ("tool", "execute_tool"), ("task", "task")]))
        <|> (text "ai.operationId" >>= vercelOp)
        <|> (ccEvent >>= (`lookup` [("api_request", "chat"), ("api_error", "chat"), ("tool_result", "execute_tool"), ("user_prompt", "user_prompt")]))
        -- Raw keys, not the derived counts: those are guarded on this very operation.
        <|> ("chat" <$ guard (isJust model && isJust (firstOf inputTokenKeys)))
    vercelOp o
      | any (`T.isSuffixOf` o) [".doGenerate", ".doStream"] = Just "chat"
      | ".doEmbed" `T.isSuffixOf` o = Just "embeddings"
      | o == "ai.toolCall" = Just "execute_tool"
      | "ai." `T.isPrefixOf` o = Just "invoke_agent"
      | otherwise = Nothing
    inference = maybe False isInferenceOp op
    tool = op == Just "execute_tool"

    model = firstOf ["gen_ai.request.model", "llm.request.model_name", "llm.model_name", "ai.model.id", "langfuse.observation.model.name"] <|> cc "model"
    responseModel = firstOf ["gen_ai.response.model", "llm.response.model_name", "ai.response.model"]
    tokens keys = guard inference *> (firstOf keys >>= num)
    inputTokenKeys = ["gen_ai.usage.input_tokens", "gen_ai.usage.prompt_tokens", "llm.token_count.prompt", "ai.usage.promptTokens", "ai.usage.inputTokens"]
    inputTokens = tokens inputTokenKeys
    outputTokens = tokens ["gen_ai.usage.output_tokens", "gen_ai.usage.completion_tokens", "llm.token_count.completion", "ai.usage.completionTokens", "ai.usage.outputTokens"]
    cacheRead = tokens ["gen_ai.usage.cache_read.input_tokens", "gen_ai.usage.cache_read_input_tokens", "llm.token_count.prompt_details.cache_read"]
    cacheWrite = tokens ["gen_ai.usage.cache_write.input_tokens", "gen_ai.usage.cache_creation.input_tokens", "gen_ai.usage.cache_creation_input_tokens", "gen_ai.usage.cache_write_input_tokens", "llm.token_count.prompt_details.cache_write"]
    ccTokens k = guard inference *> (cc k >>= num)
    -- Claude Code and pi-otel count input exclusive of the cache; the conventions count it inclusive,
    -- so their canonical counts are replaced rather than kept.
    exclusive = isJust ccEvent || text "gen_ai.system" == Just "pi"
    (rawIn, outT, readT, writeT) = case ccEvent of
      Just _ -> (ccTokens "input_tokens", ccTokens "output_tokens", ccTokens "cache_read_tokens", ccTokens "cache_creation_tokens")
      Nothing -> (inputTokens, outputTokens, cacheRead, cacheWrite)
    inT = bool id (+ sum (catMaybes [readT, writeT])) exclusive <$> rawIn
    reported = guard inference *> (firstOf ["gen_ai.usage.cost", "llm.cost.total", "gen_ai.cost.total_tokens", "pi.cost.usd"] <|> cc "cost_usd") >>= num
    cost = (,"reported" :: Text) <$> reported <|> (,"estimated") <$> estimated
    estimated = do
      price <- guard inference *> ((model <|> responseModel) >>= str >>= lookupPrice)
      guard $ isJust inT || isJust outT
      pure $ estimateCost price $ Usage (fromMaybe 0 inT) (fromMaybe 0 outT) (fromMaybe 0 readT) (fromMaybe 0 writeT)

    inputMessages = indexedMessages "llm.input_messages." "message." <|> indexedMessages "gen_ai.prompt." "" <|> (pick "ai.prompt.messages" >>= json) <|> valueMessages "user" "input.value" <|> (single "user" <$> cc "prompt")
    outputMessages = indexedMessages "llm.output_messages." "message." <|> indexedMessages "gen_ai.completion." "" <|> vercelOutput <|> valueMessages "assistant" "output.value"
    valueMessages role k = guard (op == Just "chat") *> pick k <&> \v -> fromMaybe (single role v) (json v >>= messagesOf)
    single :: Text -> AE.Value -> AE.Value
    single role content = AE.Array [AE.object ["role" .= role, "content" .= content]]
    messagesOf v = case v of
      AE.Array _ -> Just v
      AE.Object o -> KM.lookup "messages" o
      _ -> Nothing
    vercelOutput = do
      let calls = maybe [] toList (pick "ai.response.toolCalls" >>= json >>= arr)
      guard $ isJust (pick "ai.response.text") || not (null calls)
      pure $ AE.Array [AE.object ["role" .= ("assistant" :: Text), "content" .= pick "ai.response.text", "tool_calls" .= map vercelCall calls]]
    vercelCall c = AE.object ["id" .= field ["toolCallId"] c, "function" .= AE.object ["name" .= field ["toolName"] c, "arguments" .= field ["args", "input"] c]]

    -- OpenInference nests each message under "message."; OpenLLMetry does not.
    indexedMessages prefix inner = case indexed prefix kvs of
      [] -> Nothing
      msgs -> Just $ AE.Array $ V.fromList $ map (indexedMessage inner) msgs
    indexedMessage inner mm =
      let at k = HM.lookup (inner <> k) mm
          calls = [AE.object ["id" .= (HM.lookup "id" c <|> HM.lookup "tool_call.id" c), "function" .= AE.object ["name" .= (HM.lookup "name" c <|> HM.lookup "tool_call.function.name" c), "arguments" .= (HM.lookup "arguments" c <|> HM.lookup "tool_call.function.arguments" c)]] | c <- indexed (inner <> "tool_calls.") (HM.toList mm)]
       in AE.object $ ["role" .= at "role", "content" .= at "content", "tool_call_id" .= at "tool_call_id", "finish_reason" .= at "finish_reason"] <> ["tool_calls" .= calls | not (null calls)]
    -- Message content is the heaviest payload; once folded into the canonical arrays its
    -- source keys go, as do indexed keys, which would otherwise nest as {"0": …} objects.
    folded k =
      any (\p -> maybe False (isDigit . fst) (T.stripPrefix p k >>= T.uncons)) ["llm.input_messages.", "llm.output_messages.", "gen_ai.prompt.", "gen_ai.completion."]
        || (exclusive && k `elem` canonicalTokens)
        || (k `elem` ["ai.prompt.messages", "input.value"] && emitted "gen_ai.input.messages" inputMessages)
        || (k `elem` ["ai.response.text", "ai.response.toolCalls", "output.value"] && emitted "gen_ai.output.messages" outputMessages)
    emitted k v = not (HM.member k m) && isJust v
    -- Message bodies are the heaviest values: decode each array once, shared by its emit and the preview.
    givenInput = parsed "gen_ai.input.messages" <$> pick "gen_ai.input.messages"
    derivedInput = canonicalMessages <$> inputMessages
    passThrough k v = if k == "gen_ai.input.messages" then fromMaybe v givenInput else parsed k v
    parsed k v
      | k `elem` ["gen_ai.input.messages", "gen_ai.output.messages"] = canonicalMessages $ fromMaybe v (json v)
      | k `elem` ["gen_ai.system_instructions", "gen_ai.tool.definitions"] = fromMaybe v (json v)
      | otherwise = v

    finishReasons = firstOf ["gen_ai.response.finish_reasons", "llm.finish_reason", "llm.response.finish_reason", "ai.response.finishReason", "gen_ai.completion.0.finish_reason"] <|> cc "stop_reason"
    asList = \case
      v@(AE.Array _) -> v
      v -> AE.Array [v]
    conversation = firstOf ["gen_ai.conversation.id", "langfuse.session.id", "traceloop.association.properties.session_id", "ai.telemetry.metadata.sessionId", "ai.telemetry.metadata.conversationId", "ai.telemetry.metadata.threadId"] <|> (guard (isJust op) *> pick "session.id")
    provider = (firstOf ["gen_ai.provider.name", "gen_ai.system", "llm.provider", "llm.system"] <|> (text "ai.model.provider" <&> AE.String . T.takeWhile (/= '.'))) <|> ("anthropic" <$ ccEvent)
    intV = AE.Number . fromInteger . round

    derived =
      (tokenCounts <>)
        $ catMaybes
          [ emit "gen_ai.operation.name" (AE.String <$> op)
          , emit "gen_ai.provider.name" provider
          , emit "gen_ai.request.model" model
          , emit "gen_ai.response.model" responseModel
          , emit "gen_ai.usage.reasoning.output_tokens" (intV <$> tokens ["gen_ai.usage.reasoning_tokens", "llm.token_count.completion_details.reasoning"])
          , emit "gen_ai.usage.cost" (AE.toJSON . fst <$> cost)
          , emit "gen_ai.usage.cost_source" (AE.String . snd <$> cost)
          , emit "gen_ai.input.messages" derivedInput
          , emit "gen_ai.output.messages" (canonicalMessages <$> outputMessages)
          , emit "gen_ai.input.preview" (AE.String <$> ((givenInput <|> derivedInput) >>= latestUserText))
          , emit "gen_ai.response.finish_reasons" (asList <$> finishReasons)
          , emit "gen_ai.conversation.id" conversation
          , emit "gen_ai.agent.name" (firstOf ["agent.name", "traceloop.workflow.name", "ai.telemetry.functionId"])
          , emit "gen_ai.tool.name" (guard tool *> (firstOf ["tool.name", "ai.toolCall.name", "traceloop.entity.name"] <|> cc "tool_name"))
          , emit "gen_ai.tool.call.id" (guard tool *> (firstOf ["tool_call.id", "ai.toolCall.id"] <|> cc "tool_use_id"))
          , emit "gen_ai.tool.call.arguments" (guard tool *> (firstOf ["tool.parameters", "ai.toolCall.args", "ai.toolCall.input", "traceloop.entity.input", "input.value"] <|> cc "tool_parameters"))
          , emit "gen_ai.tool.call.result" (guard tool *> firstOf ["ai.toolCall.result", "ai.toolCall.output", "traceloop.entity.output", "output.value"])
          , emit "user.id" (firstOf ["langfuse.user.id", "traceloop.association.properties.user_id", "ai.telemetry.metadata.userId"])
          ]
    emit k v = guard (not $ HM.member k m) *> ((k,) <$> v)
    canonicalTokens = ["gen_ai.usage.input_tokens", "gen_ai.usage.output_tokens", "gen_ai.usage.cache_read.input_tokens", "gen_ai.usage.cache_write.input_tokens"]
    tokenCounts = catMaybes $ zipWith (\k v -> (k,) . intV <$> v <* guard (exclusive || not (HM.member k m))) canonicalTokens [inT, outT, readT, writeT]


-- | Messages in the conventions' parts shape, from OpenAI-, Anthropic-, Vercel- or
-- LangChain-shaped arrays. Already-canonical messages pass through.
--
-- >>> canonicalMessages $ AE.Array [AE.object ["role" .= ("tool" :: Text), "tool_call_id" .= ("c1" :: Text), "content" .= ("42" :: Text)]]
-- Array [Object (fromList [("parts",Array [Object (fromList [("id",String "c1"),("response",String "42"),("type",String "tool_call_response")])]),("role",String "tool")])]
-- >>> canonicalMessages $ AE.Array [AE.object ["role" .= ("assistant" :: Text), "content" .= ([AE.object ["type" .= ("tool_use" :: Text), "id" .= ("t" :: Text), "name" .= ("ls" :: Text), "input" .= AE.object []]] :: [AE.Value])]]
-- Array [Object (fromList [("parts",Array [Object (fromList [("arguments",Object (fromList [])),("id",String "t"),("name",String "ls"),("type",String "tool_call")])]),("role",String "assistant")])]
canonicalMessages :: AE.Value -> AE.Value
canonicalMessages = \case
  AE.Array msgs -> AE.Array $ V.map message msgs
  v -> v
  where
    message = \case
      AE.Object o | KM.member "parts" o -> AE.Object o
      AE.Object o ->
        let role = maybe "user" (\r -> fromMaybe r (lookup r [("human", "user"), ("ai", "assistant"), ("model", "assistant")])) (KM.lookup "role" o >>= str)
            responses = [part "tool_call_response" ["id" .= i, "response" .= KM.lookup "content" o] | Just i <- [KM.lookup "tool_call_id" o], i /= AE.Null]
            content = if null responses then foldMap contentParts (KM.lookup "content" o) else []
            calls = [part "tool_call" ["id" .= field ["id"] c, "name" .= (field ["function"] c >>= field ["name"]), "arguments" .= (field ["function"] c >>= field ["arguments"])] | c <- maybe [] toList (KM.lookup "tool_calls" o >>= arr)]
         in AE.object $ ["role" .= role, "parts" .= (responses <> content <> calls)] <> ["finish_reason" .= f | Just f <- [KM.lookup "finish_reason" o], f /= AE.Null]
      v -> AE.object ["role" .= ("user" :: Text), "parts" .= contentParts v]
    contentParts = \case
      AE.Null -> []
      AE.Array ps -> map contentPart (toList ps)
      v -> [part "text" ["content" .= v]]
    contentPart p = case field ["type"] p >>= str of
      Just t | t `elem` ["text", "input_text", "output_text"] -> part "text" ["content" .= field ["text", "content"] p]
      Just t | t `elem` ["tool-call", "tool_use", "function_call"] -> part "tool_call" ["id" .= field ["toolCallId", "id", "call_id"] p, "name" .= field ["toolName", "name"] p, "arguments" .= field ["args", "input", "arguments"] p]
      Just t | t `elem` ["tool-result", "tool_result", "function_call_output"] -> part "tool_call_response" ["id" .= field ["toolCallId", "tool_use_id", "call_id"] p, "response" .= field ["result", "output", "content"] p]
      Just t | t `elem` ["reasoning", "thinking"] -> part "reasoning" ["content" .= field ["text", "thinking", "content"] p]
      _ -> p
    part :: Text -> [(AEK.Key, AE.Value)] -> AE.Value
    part t kvs = AE.object $ ("type" .= t) : kvs


-- | The turn's question, for lists and search: the last user text in canonical messages.
latestUserText :: AE.Value -> Maybe Text
latestUserText msgs = listToMaybe [T.take 200 t | m <- reverse (maybe [] toList (arr msgs)), field ["role"] m == Just "user", p <- maybe [] toList (field ["parts"] m >>= arr), field ["type"] p == Just "text", Just (AE.String t) <- [field ["content"] p]]


-- | Groups @prefix.N.rest@ keys by N, in index order.
indexed :: Text -> [(Text, AE.Value)] -> [HM.HashMap Text AE.Value]
indexed prefix kvs =
  IntMap.elems
    $ IntMap.fromListWith
      (<>)
      [ (n, one (T.drop 1 rest, v))
      | (k, v) <- kvs
      , Just r <- [T.stripPrefix prefix k]
      , let (ix, rest) = T.breakOn "." r
      , not (T.null rest)
      , Just n <- [readMaybe (toString ix)]
      ]


field :: [Text] -> AE.Value -> Maybe AE.Value
field ks = \case
  AE.Object o -> asum [KM.lookup (AEK.fromText k) o | k <- ks] >>= \v -> v <$ guard (v /= AE.Null)
  _ -> Nothing


str :: AE.Value -> Maybe Text
str = \case
  AE.String s -> Just s
  _ -> Nothing


arr :: AE.Value -> Maybe (V.Vector AE.Value)
arr = \case
  AE.Array a -> Just a
  _ -> Nothing


-- | A JSON number, or a number sent as a string (common for attribute values).
num :: AE.Value -> Maybe Double
num = \case
  AE.Number n -> Just $ toRealFloat n
  AE.String s -> readMaybe $ toString s
  _ -> Nothing


-- | Producers send structured attributes as JSON strings.
json :: AE.Value -> Maybe AE.Value
json = \case
  AE.String s | Just (c, _) <- T.uncons (T.stripStart s), c `elem` ['[', '{'] -> AE.decodeStrict $ encodeUtf8 s
  AE.String _ -> Nothing
  v -> Just v
